#!/usr/bin/env bash
# ==============================================================================
# Мастер-скрипт запуска всех практических работ (ПР-1 - ПР-7, Вариант B)
# Дисциплина: Проектирование / Операционные системы
# Международный колледж IT и бизнеса Salymbekov University
# ==============================================================================
set -euo pipefail

BASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$BASE_DIR"

echo "======================================================================"
echo " ЗАПУСК ВСЕХ ПРАКТИЧЕСКИХ РАБОТ № 1–7 (УРОВЕНЬ B - ОСНОВНОЙ ВАРИАНТ)"
echo " Salymbekov University - Дисциплина: Операционные системы"
echo "======================================================================"

PRACTICALS=(pr01 pr02 pr03 pr04 pr05 pr06 pr07)

for pr in "${PRACTICALS[@]}"; do
    echo ""
    echo "######################################################################"
    echo ">>> ВЫПОЛНЕНИЕ: $pr/run.sh"
    echo "######################################################################"
    if [[ -f "$pr/run.sh" ]]; then
        (cd "$pr" && chmod +x run.sh && ./run.sh)
        echo ">>> [OK] $pr успешно завершена."
    else
        echo ">>> [!] Ошибка: файл $pr/run.sh не найден!"
        exit 1
    fi
done

echo ""
echo "======================================================================"
echo " [УСПЕХ] Все практические работы с 1 по 7 (Вариант B) успешно выполнены!"
echo "======================================================================"
